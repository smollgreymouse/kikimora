package config

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestWriteLeshyConfigGeneratesZones(t *testing.T) {
	path := filepath.Join(t.TempDir(), "config.toml")
	zones := []LeshyZoneSpec{
		{Name: "awg", RouteTarget: "/run/kikimora/leshy/vpn/awg.dev", Domains: []string{"chatgpt.com", "*.openai.com"}},
		{Name: "oc", RouteTarget: "/run/kikimora/leshy/vpn/oc.dev", Domains: []string{"ad-tech.ru"}, StaticRoutes: []string{"10.0.0.0/8"}},
	}
	if err := WriteLeshyConfig(path, LeshyServer{}, zones); err != nil {
		t.Fatalf("WriteLeshyConfig: %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	for _, want := range []string{
		`name = "awg"`, `route_target = "/run/kikimora/leshy/vpn/awg.dev"`, `"chatgpt.com"`,
		`name = "oc"`, `route_target = "/run/kikimora/leshy/vpn/oc.dev"`, `"ad-tech.ru"`,
		`"10.0.0.0/8"`, `listen_address = "127.0.0.1:53053"`, "Generated by Kikimora",
	} {
		if !strings.Contains(text, want) {
			t.Fatalf("generated config misses %q:\n%s", want, text)
		}
	}
	if strings.Contains(text, "primary") || strings.Contains(text, "secondary") {
		t.Fatalf("legacy zone names survived:\n%s", text)
	}
	if _, err := os.Stat(path + ".tmp"); !os.IsNotExist(err) {
		t.Fatal("temporary file left behind")
	}
}

func TestReadLeshyServerKeepsOperatorSettings(t *testing.T) {
	path := filepath.Join(t.TempDir(), "config.toml")
	content := `[server]
listen_address = "127.0.0.1:5353"
default_upstream = ["9.9.9.9:53"]

[[zones]]
name = "primary"
route_target = "/run/x.dev"
`
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	server := ReadLeshyServer(path)
	if server.ListenAddress != "127.0.0.1:5353" {
		t.Fatalf("listen = %q", server.ListenAddress)
	}
	if len(server.Upstreams) != 1 || server.Upstreams[0] != "9.9.9.9:53" {
		t.Fatalf("upstreams = %v", server.Upstreams)
	}

	defaults := ReadLeshyServer(filepath.Join(t.TempDir(), "absent.toml"))
	if defaults.ListenAddress != "127.0.0.1:53053" || len(defaults.Upstreams) == 0 {
		t.Fatalf("defaults = %#v", defaults)
	}
}
